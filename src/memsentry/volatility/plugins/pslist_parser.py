"""Normalise JSON output from Volatility's operating-system-specific pslist plugins."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from memsentry.volatility.plugins._parser_utils import (
    VolatilityPluginParseError,
    decode_rows,
    normalise_os,
    normalise_values,
    optional_bool,
    optional_int,
    optional_text,
    walk_rows,
)

PsListParseError = VolatilityPluginParseError


@dataclass(frozen=True, slots=True)
class ProcessArtifact:
    """A process record normalised from one Volatility pslist row."""

    pid: int
    process_name: str
    ppid: int | None
    offset_virtual: str | None
    offset_physical: str | None
    created_at: str | None
    exited_at: str | None
    session_id: int | None
    wow64: bool | None
    original_data: dict[str, Any]
    provenance: dict[str, Any]

    def as_repository_kwargs(self) -> dict[str, Any]:
        """Return fields accepted by ``ArtifactRepository.add_process``."""
        return {
            "pid": self.pid,
            "process_name": self.process_name,
            "ppid": self.ppid,
            "created_at": self.created_at,
            "exited_at": self.exited_at,
            "original_data": self.original_data,
            "provenance": self.provenance,
        }


@dataclass(frozen=True, slots=True)
class PsListParseResult:
    """Parsed artifacts and non-fatal row-level parsing warnings."""

    processes: tuple[ProcessArtifact, ...]
    warnings: tuple[str, ...]


class PsListParser:
    """Parse ``windows.pslist``, ``linux.pslist``, and ``mac.pslist`` JSON.

    Pass raw output generated by Volatility's ``json`` or ``jsonl`` renderer to
    :meth:`parse`. The small OS-specific methods make this a template for other
    approved plugin parsers.
    """

    _SUPPORTED_OS = frozenset({"windows", "linux", "mac"})

    def parse(
        self,
        raw_output: str | bytes | Path | Sequence[Any] | Mapping[str, Any],
        os_type: str,
    ) -> PsListParseResult:
        """Decode and normalise raw Volatility output for ``os_type``.

        Invalid rows do not abort an otherwise usable plugin result. They are
        skipped and recorded in ``warnings`` for the plugin run audit record.
        """
        normalised_os = self._normalise_os(os_type)
        rows = decode_rows(raw_output, "pslist")
        parser = {
            "windows": self.windows_parser,
            "linux": self.linux_parser,
            "mac": self.mac_parser,
        }[normalised_os]

        processes: list[ProcessArtifact] = []
        warnings: list[str] = []
        for row_number, depth, row in walk_rows(rows):
            try:
                processes.append(parser(row, row_number=row_number, depth=depth))
            except PsListParseError as error:
                warnings.append(str(error))
        return PsListParseResult(tuple(processes), tuple(warnings))

    def linux_parser(
        self, row: Mapping[str, Any], *, row_number: int = 1, depth: int = 0
    ) -> ProcessArtifact:
        """Normalise a row from ``linux.pslist.PsList``."""
        return self._build_process(row, row_number=row_number, depth=depth, os_type="linux")

    def windows_parser(
        self, row: Mapping[str, Any], *, row_number: int = 1, depth: int = 0
    ) -> ProcessArtifact:
        """Normalise a row from ``windows.pslist.PsList``."""
        return self._build_process(row, row_number=row_number, depth=depth, os_type="windows")

    def mac_parser(
        self, row: Mapping[str, Any], *, row_number: int = 1, depth: int = 0
    ) -> ProcessArtifact:
        """Normalise a row from ``mac.pslist.PsList``."""
        return self._build_process(row, row_number=row_number, depth=depth, os_type="mac")

    def _build_process(
        self, row: Mapping[str, Any], *, row_number: int, depth: int, os_type: str
    ) -> ProcessArtifact:
        values = normalise_values(row)
        pid = self._required_int(values, ("pid",), row_number, "PID")
        process_name = self._required_text(
            values, ("imagefilename", "comm", "name"), row_number, "process name"
        )
        ppid = self._optional_int(values, ("ppid",), row_number, "PPID")

        return ProcessArtifact(
            pid=pid,
            process_name=process_name,
            ppid=ppid,
            offset_virtual=self._optional_text(values, ("offsetv", "offset")),
            offset_physical=self._optional_text(values, ("offsetp",)),
            created_at=self._optional_text(values, ("createtime", "creationtime", "starttime")),
            exited_at=self._optional_text(values, ("exittime",)),
            session_id=self._optional_int(values, ("sessionid",), row_number, "SessionId"),
            wow64=self._optional_bool(values, ("wow64",), row_number, "Wow64"),
            original_data=dict(row),
            provenance={
                "source_plugin": f"{os_type}.pslist.PsList",
                "source_row": row_number,
                "source_tree_depth": depth,
            },
        )

    @staticmethod
    def _normalise_os(os_type: str) -> str:
        return normalise_os(os_type, PsListParser._SUPPORTED_OS)

    @staticmethod
    def _required_int(
        values: Mapping[str, Any], names: tuple[str, ...], row_number: int, label: str
    ) -> int:
        parsed = optional_int(values, names)
        if parsed is None or parsed < 0:
            raise PsListParseError(f"pslist row {row_number} has no valid {label}; row skipped.")
        return parsed

    @staticmethod
    def _optional_int(
        values: Mapping[str, Any], names: tuple[str, ...], row_number: int, label: str
    ) -> int | None:
        value = next(
            (values[name] for name in names if name in values and values[name] is not None), None
        )
        if value is None:
            return None
        parsed = optional_int({"value": value}, ("value",))
        if parsed is None or parsed < 0:
            raise PsListParseError(f"pslist row {row_number} has invalid {label}; row skipped.")
        return parsed

    @staticmethod
    def _required_text(
        values: Mapping[str, Any], names: tuple[str, ...], row_number: int, label: str
    ) -> str:
        value = optional_text(values, names)
        if value is None:
            raise PsListParseError(f"pslist row {row_number} has no valid {label}; row skipped.")
        return value

    @staticmethod
    def _optional_text(values: Mapping[str, Any], names: tuple[str, ...]) -> str | None:
        return optional_text(values, names)

    @staticmethod
    def _optional_bool(
        values: Mapping[str, Any], names: tuple[str, ...], row_number: int, label: str
    ) -> bool | None:
        parsed = optional_bool(values, names)
        if parsed is None and any(name in values and values[name] is not None for name in names):
            raise PsListParseError(f"pslist row {row_number} has invalid {label}; row skipped.")
        return parsed
